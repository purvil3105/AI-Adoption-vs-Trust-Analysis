"""Generate reports/data_dictionary.md: every harmonised variable, its raw column and exact wording per year.

Usage:  python -m src.data_dictionary
"""
import html
import re

import pandas as pd

from src.config import RAW, ROOT, YEARS
from src.load import load_crosswalk


def schema_text(year: int) -> dict[str, str]:
    s = pd.read_csv(RAW / str(year) / "schema.csv", dtype=str).fillna("")
    out = {}
    for q, text in zip(s["qname"], s["question"]):
        t = html.unescape(re.sub(r"<[^>]+>", " ", text))
        out.setdefault(q, re.sub(r"\s+", " ", t).strip())
    return out


def wording(col_cell: str, texts: dict[str, str]) -> str:
    parts = []
    for raw in col_cell.replace("(!)", "").split("+"):
        name = raw.strip()
        key = name.replace("AIToolCurrently Using", "AITool").replace("AIToolCurrently mostly AI", "AITool")
        key = key.replace("AIToolCurrently partially AI", "AITool")
        key = re.sub(r"HaveWorkedWith$", "", key)
        if key in texts:
            parts.append(f"`{name}`: {texts[key]}")
        elif name:
            parts.append(f"`{name}`")
    return "<br>".join(parts) if parts else "*not asked*"


def main() -> None:
    cw = load_crosswalk()
    texts = {y: schema_text(y) for y in YEARS}
    lines = [
        "# Data dictionary",
        "",
        "Generated by `python -m src.data_dictionary` from the official `schema.csv` files and "
        "`mappings/question_crosswalk.csv`. Recodes are in `mappings/value_maps.yaml`.",
        "",
        "**Comparability tiers:** A = identical; B = comparable after a documented recode; "
        "B- = similar concept, used only for robustness; C = not comparable across years (within-year analysis only).",
        "",
        "> **2023 column swap:** in 2023 the trust question is stored in `AIBen` and the benefits question in `AIAcc` "
        "(the official schema confirms this). From 2024 on, the names match their content.",
        "",
    ]
    for _, r in cw.iterrows():
        lines += [f"## `{r.harmonised_var}` - tier {r.comparability}", "",
                  f"*Used in:* {r.used_in}  ", f"*Rule:* {r.harmonisation_rule}", "",
                  "| Year | Raw column and question wording | Asked to |", "|---|---|---|"]
        for y in YEARS:
            lines.append(f"| {y} | {wording(r[f'col_{y}'], texts[y])} | {r[f'asked_to_{y}'] or '-'} |")
        lines += ["", f"*Wording changed:* {r.wording_changed or '-'} &middot; *Options changed:* {r.options_changed or '-'}", ""]

    lines += ["## Derived analysis columns (`respondents.parquet`)", "",
              "| Column | Definition |", "|---|---|",
              "| `is_professional` | 1 if MainBranch = 'I am a developer by profession' |",
              "| `uses_ai` / `uses_or_plans_ai` | 1/0 from ai_use_status; blank if the question was not answered |",
              "| `trust_score` | 1 = highly distrust ... 5 = highly trust |",
              "| `trusts_ai` / `distrusts_ai` / `highly_distrusts_ai` | 1/0 from trust_score (neutral = 0 for both) |",
              "| `in_trust_base_users` | 1 = current AI user who answered the trust question (comparable base) |",
              "| `in_trust_base_official` | 1 = answered the trust question (Stack Overflow's published base; differs by year) |",
              "| `exp_bucket` | years_code bucketed 0-4 / 5-9 / 10-19 / 20-29 / 30+ |",
              "| `country_group` | 15 largest countries (pooled) + 'Other' |",
              "| `task_*` | 1/0 currently uses AI for the task; blank if the task question was skipped or the task was not offered that year |",
              "| `frus_*` | 1/0 2025 frustration selected; blank if the question was skipped |",
              "| `tool_*`, `n_ai_tools` | AI tools used (2025 = LLM models + AI editors, not products) |", ""]
    out = ROOT / "reports" / "data_dictionary.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
